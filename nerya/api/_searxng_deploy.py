def status(workspace_root: Path | str, *, base_url: str = "") -> dict[str, Any]:
    ws = _Workspace.at(workspace_root)
    state = _read_state(ws)
    container_name = state.get("container_name") or _DEFAULT_CONTAINER
    has_docker = _docker_available()
    running = has_docker and _container_running(container_name)
    probe_url = (base_url or state.get("base_url")
                 or f"http://127.0.0.1:{state.get('host_port') or _DEFAULT_HOST_PORT}").rstrip("/")
    probe = _http_probe(probe_url) if probe_url else {"ok": False,
                                                       "error": "no probe url"}
    return {
        "ok": True,
        "docker_available": has_docker,
        "container_name": container_name,
        "container_running": running,
        "image": state.get("image") or _DEFAULT_IMAGE,
        "host_port": int(state.get("host_port") or _DEFAULT_HOST_PORT),
        "base_url": probe_url,
        "config_dir": str(ws.config_dir),
        "state_file": str(ws.state_file),
        "deployed": bool(state),
        "probe": probe,
    }


def deploy(
    workspace_root: Path | str,
    *,
    host_port: int | None = None,
    image: str | None = None,
    container_name: str | None = None,
    rebuild: bool = False,
) -> dict[str, Any]:
    ws = _Workspace.at(workspace_root)
    if not _docker_available():
        return {
            "ok": False,
            "error": "docker_unavailable",
            "detail": "docker CLI not on PATH; install Docker Desktop or use a remote SearXNG URL",
        }

    state = _read_state(ws)
    cname = container_name or state.get("container_name") or _DEFAULT_CONTAINER
    img = image or state.get("image") or _DEFAULT_IMAGE
    port = int(host_port or state.get("host_port") or _DEFAULT_HOST_PORT)
    base_url = f"http://127.0.0.1:{port}"

    settings_path = _ensure_config(ws, port=port)

    # If a container with this name exists, remove first when rebuilding.
    info = _docker_inspect(cname)
    exists = bool(info)
    if exists:
        if rebuild:
            subprocess.run(["docker", "rm", "-f", cname],
                           capture_output=True, text=True, timeout=20)
            exists = False
        else:
            running = _container_running(cname)
            if not running:
                # try to start it again
                start_res = subprocess.run(
                    ["docker", "start", cname],
                    capture_output=True, text=True, timeout=20,
                )
                if start_res.returncode != 0:
                    return {
                        "ok": False,
                        "error": "container_start_failed",
                        "detail": (start_res.stderr or start_res.stdout)[:1000],
                    }

    if not exists:
        # Pre-pull (best effort; ignore failure since `run` will pull too).
        subprocess.run(["docker", "pull", img],
                       capture_output=True, text=True, timeout=180)
        cmd = [
            "docker", "run", "-d",
            "--name", cname,
            "--restart", "unless-stopped",
            "-p", f"127.0.0.1:{port}:8080",
            "-v", f"{settings_path.parent}:/etc/searxng",
            "-e", "SEARXNG_BASE_URL=" + base_url + "/",
            img,
        ]
        run_res = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        if run_res.returncode != 0:
            return {
                "ok": False,
                "error": "docker_run_failed",
                "detail": (run_res.stderr or run_res.stdout)[:2000],
            }

    # Persist state
    new_state = {
        "container_name": cname,
        "image": img,
        "host_port": port,
        "base_url": base_url,
        "deployed_at": int(time.time()),
        "settings_yml": str(settings_path),
    }
    _write_state(ws, new_state)

    # Wait briefly for the container to come up (up to ~10s).
    probe: dict[str, Any] = {"ok": False, "error": "not probed yet"}
    for _ in range(10):
        probe = _http_probe(base_url)
        if probe.get("ok"):
            break
        time.sleep(1.0)

    return {
        "ok": True,
        "container_name": cname,
        "image": img,
        "host_port": port,
        "base_url": base_url,
        "settings_yml": str(settings_path),
        "probe": probe,
    }


def teardown(workspace_root: Path | str, *,
             remove: bool = True) -> dict[str, Any]:
    ws = _Workspace.at(workspace_root)
    state = _read_state(ws)
    cname = state.get("container_name") or _DEFAULT_CONTAINER
    if not _docker_available():
        return {"ok": False, "error": "docker_unavailable"}
    info = _docker_inspect(cname)
    if not info:
        return {"ok": True, "removed": False, "running": False,
                "detail": "no container present"}
    cmd = ["docker", "rm", "-f", cname] if remove else ["docker", "stop", cname]
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    if res.returncode != 0:
        return {
            "ok": False,
            "error": "docker_remove_failed" if remove else "docker_stop_failed",
            "detail": (res.stderr or res.stdout)[:1000],
        }
    if remove:
        # Keep config — operator may want to redeploy. State file just
        # carries whatever we last wrote; clearing it would destroy port
        # preference / image override silently.
        new_state = dict(state)
        new_state["torn_down_at"] = int(time.time())
        _write_state(ws, new_state)
    return {"ok": True, "removed": bool(remove), "running": False}


__all__ = ["status", "deploy", "teardown"]
