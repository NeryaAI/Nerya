"""Local SearXNG container lifecycle helpers.

Provides a thin wrapper that:

- generates a minimal SearXNG ``settings.yml`` with ``formats: [html, json]``
  enabled (required by the :class:`SearXNGAdapter`),
- starts a Docker container bound to a configurable port,
- tracks pid / container-id state in
  ``<workspace>/state/searxng/state.json`` so the dashboard can render
  status across restarts,
- supports stop / status probes / config rotation.

The deployment is **opt-in** — nothing happens until the dashboard
explicitly calls ``deploy()``. We never auto-start a container.

Docker is the only supported runtime here. If the operator wants to run
SearXNG some other way (compose, k8s, hosted), they just type the URL
into the dashboard and we leave the deploy block alone.
"""

from __future__ import annotations

import json
import os
import secrets
import shutil
import socket
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.error import URLError
from urllib.request import Request, urlopen


_DEFAULT_IMAGE = "searxng/searxng:latest"
_DEFAULT_CONTAINER = "nerya-searxng"
_DEFAULT_HOST_PORT = 8888
_PROBE_TIMEOUT_S = 4.0


@dataclass
class _Workspace:
    root: Path
    state_dir: Path
    config_dir: Path
    state_file: Path

    @classmethod
    def at(cls, workspace_root: Path | str) -> "_Workspace":
        root = Path(workspace_root)
        state_dir = root / "state" / "searxng"
        config_dir = root / "state" / "searxng" / "config"
        return cls(
            root=root,
            state_dir=state_dir,
            config_dir=config_dir,
            state_file=state_dir / "state.json",
        )


def _read_state(ws: _Workspace) -> dict[str, Any]:
    if not ws.state_file.exists():
        return {}
    try:
        return json.loads(ws.state_file.read_text(encoding="utf-8")) or {}
    except Exception:
        return {}


def _write_state(ws: _Workspace, data: dict[str, Any]) -> None:
    ws.state_dir.mkdir(parents=True, exist_ok=True)
    ws.state_file.write_text(
        json.dumps(data, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def _docker_available() -> bool:
    return shutil.which("docker") is not None


def _docker_inspect(name: str) -> dict[str, Any]:
    try:
        res = subprocess.run(
            ["docker", "inspect", name],
            capture_output=True, text=True, timeout=10,
        )
    except Exception:
        return {}
    if res.returncode != 0 or not res.stdout.strip():
        return {}
    try:
        rows = json.loads(res.stdout)
    except Exception:
        return {}
    return rows[0] if isinstance(rows, list) and rows else {}


def _container_running(name: str) -> bool:
    info = _docker_inspect(name)
    state = (info.get("State") or {}) if isinstance(info, dict) else {}
    return bool(state.get("Running"))


def _http_probe(base_url: str, *, timeout_s: float = _PROBE_TIMEOUT_S) -> dict[str, Any]:
    base = base_url.rstrip("/")
    started = time.monotonic()
    try:
        req = Request(
            f"{base}/search?q=ping&format=json",
            headers={"Accept": "application/json", "User-Agent": "Nerya/probe"},
        )
        with urlopen(req, timeout=timeout_s) as resp:
            body = resp.read(2048)
            ct = resp.headers.get("Content-Type", "")
            elapsed = int((time.monotonic() - started) * 1000)
            return {
                "ok": True,
                "status": resp.status,
                "content_type": ct,
                "elapsed_ms": elapsed,
                "body_preview": body.decode("utf-8", errors="replace")[:200],
            }
    except URLError as exc:
        return {
            "ok": False,
            "elapsed_ms": int((time.monotonic() - started) * 1000),
            "error": f"URLError: {getattr(exc, 'reason', exc)}",
        }
    except socket.timeout:
        return {
            "ok": False,
            "elapsed_ms": int((time.monotonic() - started) * 1000),
            "error": "timeout",
        }
    except Exception as exc:  # noqa: BLE001
        return {
            "ok": False,
            "elapsed_ms": int((time.monotonic() - started) * 1000),
            "error": f"{type(exc).__name__}: {exc}",
        }


def _settings_yml(*, secret: str, port: int) -> str:
    return f"""# Auto-generated by Nerya — do not edit by hand.
use_default_settings: true

server:
  bind_address: "0.0.0.0"
  port: 8080
  secret_key: "{secret}"
  limiter: false
  image_proxy: true

ui:
  static_use_hash: true

search:
  formats:
    - html
    - json
  safe_search: 0
  autocomplete: ""
  default_lang: "auto"
"""


def _ensure_config(ws: _Workspace, *, port: int) -> Path:
    ws.config_dir.mkdir(parents=True, exist_ok=True)
    settings_path = ws.config_dir / "settings.yml"
    if not settings_path.exists():
        secret = secrets.token_hex(32)
        settings_path.write_text(_settings_yml(secret=secret, port=port),
                                 encoding="utf-8")
    return settings_path


